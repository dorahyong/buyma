def _brickmansion_bracket(m):
    """대괄호 정리:
       - 콜라보 [A x B] (x/X/× 포함) → 대괄호만 벗기고 콜라보 텍스트는 남긴다
       - 그 외 [브랜드/홍보] (last size, brand sale, adizero sale, 본사공식, jerusalem sandals 등) → 통째 지운다
    """
    inner = m.group(1)
    return f" {inner} " if re.search(r'[Xx×]', inner) else " "


